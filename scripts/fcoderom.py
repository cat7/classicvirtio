# Build a PCI expansion ROM whose FCode attaches an NDRV to its device
# node as "driver,AAPL,MacOS,PowerPC", so ROM-based Open Firmware (Old
# World, Apple OF 3/4) can load the driver without ndrvloader.
#
# Usage: fcoderom.py [--variant alloc|encplus|rom] [--debug] [--toke PATH]
#                    NDRV VENDOR DEVICE CLASS OUT.rom
#   alloc:   copy string chunks into one alloc-mem buffer
#   encplus: encode-bytes per chunk, joined with encode+
#   rom:     raw NDRV appended to the ROM image, read via map-in (default)
# --debug publishes dbg-* progress properties on the node.

import argparse
import struct
import subprocess
import sys

CHUNK = 250  # b(") strings hold at most 255 bytes

ap = argparse.ArgumentParser()
ap.add_argument('--variant', choices=['alloc', 'encplus', 'rom'], default='rom')
ap.add_argument('--debug', action='store_true')
ap.add_argument('--toke', default='toke')
ap.add_argument('ndrv')
ap.add_argument('vendor')
ap.add_argument('device')
ap.add_argument('klass')
ap.add_argument('out')
a = ap.parse_args()

ndrv = open(a.ndrv, 'rb').read()
dbg = a.debug


def mark(step):
    return ('%d encode-int " dbg-step" property' % step) if dbg else ''


def forth(data_off):
    L = []
    L.append('\\ Generated by fcoderom.py (%s) from %s' % (a.variant, a.ndrv.split('/')[-1]))
    L.append('tokenizer[')
    L.append('h# 1 SET-REV-LEVEL')
    L.append('h# %s h# %s h# %s' % (a.vendor, a.device, a.klass))
    L.append(']tokenizer')
    L.append('pci-header')
    L.append('fcode-version2')
    L.append('hex')

    # Mac OS matches the NDRV to the node by "name"/"compatible"; with FCode
    # present the firmware may not give the node its default pciVVVV,DDDD name.
    name = 'pci%s,%s' % (a.vendor.lower(), a.device.lower())
    L.append('" %s" device-name' % name)
    L.append('" %s" encode-string " compatible" property' % name)

    # ROM-based OF (Old World at least) only assigns the BARs that the FCode
    # lists in "reg", so size each BAR and list it. A 64-bit memory BAR is
    # listed as 32-bit: OF fills the low half and the high half stays 0.
    L.append('''
0 value boff  0 value val  0 value size  0 value hi
: cfg-l@ ( cfg -- l ) " config-l@" $call-parent ;
: cfg-l! ( l cfg -- ) " config-l!" $call-parent ;
: probe-bar ( -- )
  my-space boff +  dup cfg-l@ >r  dup -1 swap cfg-l!
  dup cfg-l@ to val  r> swap cfg-l! ;
: phys>enc ( phys.hi -- adr len )
  encode-int 0 encode-int encode+ 0 encode-int encode+ ;
: reg-entry ( adr len phys.hi size -- adr' len' )
  >r phys>enc encode+ 0 encode-int encode+ r> encode-int encode+ ;
: make-reg ( -- )
  my-space phys>enc 0 encode-int encode+ 0 encode-int encode+
  10 to boff
  begin boff 28 < while
    probe-bar
    val if
      val 1 and if
        val fffffffc and invert 1+ to size
        my-space boff + 01000000 or to hi
        boff 4 + to boff
      else
        val fffffff0 and invert 1+ to size
        my-space boff + 02000000 or  val 8 and if 40000000 or then  to hi
        val 6 and 4 = if boff 8 + else boff 4 + then to boff
      then
      hi size reg-entry
    else
      boff 4 + to boff
    then
  repeat
  " reg" property ;
make-reg''')
    L.append(mark(1))
    L.append('d# %d constant ndrv-len' % len(ndrv))

    if a.variant == 'alloc':
        L.append('ndrv-len alloc-mem constant ndrv-buf')
        if dbg:
            L.append('ndrv-buf encode-int " dbg-buf" property')
        L.append(mark(2))
        for i, off in enumerate(range(0, len(ndrv), CHUNK)):
            hexbytes = ' '.join('%02x' % b for b in ndrv[off:off+CHUNK])
            L.append('" "(%s)" ndrv-buf h# %x + swap move' % (hexbytes, off))
            if dbg and i % 32 == 31:
                L.append('h# %x encode-int " dbg-off" property' % off)
        L.append('ndrv-buf ndrv-len encode-bytes')
        L.append(mark(3))
        L.append('" driver,AAPL,MacOS,PowerPC" property')
        L.append(mark(4))
        L.append('ndrv-buf ndrv-len free-mem')

    elif a.variant == 'encplus':
        L.append(mark(2))
        for i, off in enumerate(range(0, len(ndrv), CHUNK)):
            hexbytes = ' '.join('%02x' % b for b in ndrv[off:off+CHUNK])
            L.append('" "(%s)" encode-bytes%s' % (hexbytes, '' if off == 0 else ' encode+'))
            if dbg and i % 32 == 31:
                L.append('h# %x encode-int " dbg-off" property' % off)
        L.append(mark(3))
        L.append('" driver,AAPL,MacOS,PowerPC" property')
        L.append(mark(4))

    else:  # rom: the NDRV follows the FCode image inside this ROM
        L.append('h# %08x constant data-off' % data_off)
        L.append('''
0 value rom-va
: rom-pa ( -- pa ) my-space 30 + cfg-l@ fffff800 and ;''')
        if dbg:
            L.append('rom-pa encode-int " dbg-rompa" property')
        L.append('rom-pa 0 82000000 data-off ndrv-len + " map-in" $call-parent to rom-va')
        if dbg:
            L.append('rom-va encode-int " dbg-romva" property')
            L.append('rom-va data-off + l@ encode-int " dbg-sig" property')
        L.append(mark(2))
        L.append('rom-va data-off + ndrv-len encode-bytes')
        L.append(mark(3))
        L.append('" driver,AAPL,MacOS,PowerPC" property')
        L.append(mark(4))
        L.append('rom-va data-off ndrv-len + " map-out" $call-parent')

    L.append('fcode-end')
    L.append('pci-header-end')
    return '\n'.join(l for l in L if l) + '\n'


def tokenize(src):
    fth = a.out.rsplit('.', 1)[0] + '.fth'
    open(fth, 'w').write(src)
    r = subprocess.run([a.toke, fth], capture_output=True, text=True)
    if r.returncode or 'Error' in r.stdout + r.stderr:
        sys.exit('toke failed:\n' + r.stdout + r.stderr)
    return open(fth.rsplit('.', 1)[0] + '.fc', 'rb').read()


img = tokenize(forth(0))
if a.variant == 'rom':
    # The literal is fixed width, so the image size does not depend on it
    img = tokenize(forth(len(img)))
    img = bytearray(img + ndrv)
    img += bytes(-len(img) % 512)
    pcir = struct.unpack_from('<H', img, 0x18)[0]
    struct.pack_into('<H', img, pcir + 0x10, len(img) // 512)
open(a.out, 'wb').write(img)
print('%s: %d bytes (%s%s)' % (a.out, len(img), a.variant, ', debug' if dbg else ''))
